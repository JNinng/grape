package biz

// Tokenizer 是词元切分契约：摄取写路径（切片正文分词建词法索引）与查询
// 路径（检索查询分词）必须共用同一实现实例——两端口径漂移即静默漏召回，
// 这是词法召回的正确性前提。实现落在 data 层能力目录（与 Embedder /
// Completer 同形），当前为纯 Go 分词（go-ego/gse，词典经 embed 进二进制），
// 不依赖数据库侧分词扩展（zhparser / pgroonga 会把口径绑死在部署扩展上）。
//
// 契约只声明形状，本层不消费它；两侧消费方是向量仓储的写入（建索引）与
// 检索（查询分词），同一实例由 wire 装配透传保证。
type Tokenizer interface {
	// Tokens 把文本切成词元序列：同一文本重复调用必须产出同一序列
	//（确定性），空白文本返回空切片不报错。词元已按查询口径归一
	//（小写、去首尾空白），写入侧与查询侧以同一归一结果比对。
	Tokens(text string) []string
}
